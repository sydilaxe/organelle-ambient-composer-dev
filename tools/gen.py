"""Build the Organelle patch: python3 gen.py [outdir]  (default ../patches/Amble)."""
import os
import sys
from pdlib import Canvas
import gen_brain as B
import gen_ui as U
import gen_dsp as D
import gen_live as L
import gen_oled as O
import gen_setup as S
import gen_sounds as SN

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "patches", "Amble")


def main_patch():
    m = Canvas(w=1500, h=900)
    m.comment("AMBLE - generated by tools/gen.py, edit the generator rather than this file", 20, 5)
    lb = m.obj("loadbang", 20, 40)
    t = m.obj("t b b b b", 20, 65)
    m.c(lb, 0, t, 0)
    m.c(t, 3, m.obj("s ac-init", 230, 95), 0)
    m.c(t, 2, m.obj("s ac-loadsettings", 160, 120), 0)
    m.c(t, 1, m.obj("s ac-seedinit", 90, 145), 0)
    tk = m.obj("t b b b b b", 20, 120)
    m.c(t, 0, tk, 0)
    for i, n in enumerate(("ac-ctick", "ac-rtick", "ac-btick", "ac-dtick", "ac-ttick")):
        m.c(tk, i, m.obj("s " + n, 20 + i * 90, 150), 0)
    m.c(m.m(m.obj("loadbang", 400, 40), "0"), 0, m.obj("s midiOutGate", 400, 90), 0)
    m.comment("control", 20, 200)
    for i, sub in enumerate((B.globals_(), B.rng(), B.seed(), B.piece(), B.section(), B.change(), B.layers(),
                             B.players(), B.capture(), B.verb(), B.stereo(), B.rhythm(), L.midi_in(), L.live(), L.memories(), L.tables(),
                             O.oled(), S.settings(), S.setup(), S.midi_out(), S.clock_in(), S.cpu_guard(),
                             U.knobs(), U.keys(), U.screen())):
        m.sub(sub, 20 + (i % 4) * 110, 225 + (i // 4) * 30)
    m.comment("sound", 20, 340)
    for k in range(4):
        m.obj(f"acvoice {k}", 20 + k * 90, 365)
        m.obj(f"amlive {k}", 400 + k * 90, 365)
    for i, sub in enumerate((D.drone(), D.tex_rain(), D.tex_wind(), D.tex_ember(), D.tex_chirp(), D.cloud(),
                             D.cloud_write(), D.bells(), D.motion(), D.inp(), D.reso(), D.tape(), D.bands(),
                             D.mem_rec(), D.mem_play(), D.master())
                             + tuple(f() for f in SN.NEW_DRONES + SN.NEW_TEXTURES + SN.ATMOS) + (SN.sub(), SN.vocoder())):
        m.sub(sub, 20 + (i % 4) * 110, 400 + (i // 4) * 30)
    m.obj(f"array define acbuf {D.CLOUD_LEN}", 20, 510)
    return m


def build(out=OUT):
    os.makedirs(out, exist_ok=True)
    main_patch().save(os.path.join(out, "main.pd"))
    D.voice().save(os.path.join(out, "acvoice.pd"))
    D.live_voice().save(os.path.join(out, "amlive.pd"))
    seedf = os.path.join(out, "seed.txt")
    if not os.path.exists(seedf):
        open(seedf, "w").write("0;\n")
    sf = os.path.join(out, "settings.txt")
    if not os.path.exists(sf):
        import gen_setup
        from data import PAGES
        from data import FILE_KNOBS
        kd = [d for p in PAGES for _, _, d in p]
        vals = kd[:FILE_KNOBS] + [1, 0, -1, 0, 0.7, 48, 1, 1.2, 0, 1, 0.8, 0, 0, 48, 1] + kd[FILE_KNOBS:] + [0, 0, 0, 0] + [0, 0, 0, 2, 0, 0, 0]
        open(sf, "w").write(" ".join(f"{v:g}" for v in vals) + ";\n")
    # Pd start-up options: the Organelle OS starts Pd with a 6 ms audio buffer and appends the patch folder's
    # pd-opts.txt, so a later -audiobuf wins. 25 ms gives Pd room for brief spikes (screen, section changes,
    # reverb crossfades) that made the audio crackle at a low average load; it adds about 19 ms to live playing.
    open(os.path.join(out, "pd-opts.txt"), "w").write("-audiobuf 25\n")
    from readme_text import PATCH_README
    open(os.path.join(out, "README.txt"), "w").write(PATCH_README)
    return out


if __name__ == "__main__":
    print(build())
